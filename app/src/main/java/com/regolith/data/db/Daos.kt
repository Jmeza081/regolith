        update(merged)
        return merged
    }

    /**
     * Every moment frame held for one film, so a chapter save can tell which
     * of them no longer answers to a mark (see
     * `ArtworkRepository.pruneMoments`).
     */
    @Query("SELECT * FROM artwork WHERE ownerType = 'moment' AND ownerId = :fileId")
    suspend fun momentsOf(fileId: Long): List<ArtworkEntity>

    /** One moment's rows, dropped when its mark moves or goes. */
    @Query("DELETE FROM artwork WHERE ownerType = 'moment' AND ownerId = :fileId AND ownerVariant = :startMs")
    suspend fun deleteMoment(fileId: Long, startMs: String)

    @Query("SELECT COUNT(*) FROM artwork WHERE source != 'PLACEHOLDER'")
    fun observeCount(): Flow<Int>

    /** Rows the app made itself, as opposed to an image found on the share. */
    /**
     * Artwork whose owner has been deleted.
     *
     * `artwork` deliberately has NO foreign key — it is keyed by a loose
     * (ownerType, ownerId) pair so a rescan that keeps a file id keeps its
     * pictures (guardrail G5). The cost of that is exactly this: when rows
     * really do go, nothing collects the images behind them, and before the
     * startup sweep existed a disconnected server left its whole wall of
     * thumbnails on disk and in the Settings count forever.
     */
    @Query(
        "SELECT * FROM artwork WHERE " +
            "(ownerType IN ('file', 'moment') AND ownerId NOT IN (SELECT id FROM media_files)) OR " +
            "(ownerType = 'folder' AND ownerId NOT IN (SELECT id FROM folders))",
    )
    suspend fun orphans(): List<ArtworkEntity>

    @Query("DELETE FROM artwork WHERE id IN (:ids)")
    suspend fun deleteByIds(ids: List<Long>)

    @Query("SELECT * FROM artwork WHERE source IN ('FRAMEGRAB', 'MOSAIC', 'PLACEHOLDER')")
    suspend fun generated(): List<ArtworkEntity>

    @Query("DELETE FROM artwork WHERE source IN ('FRAMEGRAB', 'MOSAIC', 'PLACEHOLDER')")
    suspend fun deleteGenerated()

    /**
     * Drops a folder's placeholder so the next request tries again. A folder
     * scanned before its videos were copied in has nothing to make a mosaic
     * from; this is how the scan that finds them undoes that.
     */
    @Query("DELETE FROM artwork WHERE ownerType = 'folder' AND ownerId = :folderId AND source = 'PLACEHOLDER'")
    suspend fun deleteFolderPlaceholder(folderId: Long): Int

    /** Drops a folder's mosaic so the next request re-runs the source order and finds the new sidecar. */
    @Query("DELETE FROM artwork WHERE ownerType = :ownerType AND ownerId = :ownerId AND source = 'MOSAIC'")
    suspend fun deleteMosaic(ownerType: String, ownerId: Long)

    @Query("DELETE FROM artwork")
    suspend fun deleteAll()
}

@Dao
interface TransferDao {
    @Query("SELECT * FROM transfers ORDER BY createdAtMs DESC")
    fun observeAll(): Flow<List<TransferEntity>>

    @Query("SELECT * FROM transfers WHERE fileId = :fileId")
    fun observeForFile(fileId: Long): Flow<TransferEntity?>

    @Query("SELECT * FROM transfers WHERE fileId = :fileId")
    suspend fun byFile(fileId: Long): TransferEntity?

    @Query("SELECT * FROM transfers WHERE fileId = :fileId AND status = 'DONE'")
    fun doneForFileBlocking(fileId: Long): TransferEntity?

    @Query("SELECT * FROM transfers WHERE fileId = :fileId AND status = 'DONE'")
    suspend fun doneForFile(fileId: Long): TransferEntity?

    @Query("SELECT * FROM transfers WHERE status = :status")
    suspend fun allWith(status: String): List<TransferEntity>

    @Insert
    suspend fun insert(transfer: TransferEntity): Long

    @Update
    suspend fun update(transfer: TransferEntity)

    @Query("DELETE FROM transfers WHERE fileId = :fileId")
    suspend fun deleteForFile(fileId: Long)

    @Query("DELETE FROM transfers WHERE status = 'FAILED'")
    suspend fun deleteFailed()

    /** Rows a dead process left RUNNING; WorkManager re-runs the work, so they become QUEUED. */
    @Query("UPDATE transfers SET status = 'QUEUED' WHERE status = 'RUNNING'")
    suspend fun requeueRunning()

    /**
     * The next row to copy, oldest first.
     *
     * PAUSED counts as pending: the share dropped out mid-copy and the file
     * resumes from its `.part` length, so it is waiting for a turn like
     * anything else. The queue worker re-asks this after every file rather
     * than taking a snapshot, which is what lets rows added mid-drain join
     * the batch already running.
     */
    @Query("SELECT * FROM transfers WHERE status IN ('QUEUED', 'PAUSED') ORDER BY createdAtMs, id LIMIT 1")
    suspend fun nextQueued(): TransferEntity?

    /** How many rows are still owed: the notification's "of 34". */
    @Query("SELECT COUNT(*) FROM transfers WHERE status IN ('QUEUED', 'PAUSED', 'RUNNING')")
    suspend fun activeCount(): Int

    @Query("SELECT COUNT(*) FROM transfers WHERE status IN ('QUEUED', 'PAUSED', 'RUNNING')")
    fun observeActiveCount(): Flow<Int>

    /** Bytes owed and bytes copied across everything pending, for the batch progress bar. */
    @Query(
        "SELECT COALESCE(SUM(totalBytes), 0) AS total, COALESCE(SUM(bytesDone), 0) AS done " +
            "FROM transfers WHERE status IN ('QUEUED', 'PAUSED', 'RUNNING')",
    )
    suspend fun activeBytes(): ByteTally

    /**
     * Stop everything pending. FAILED with CANCELLED rather than deleted,
     * so a stopped batch lands in the design's "Failed · N" section with
     * its "Try again" instead of vanishing, and the bytes already copied
     * stay on disk for the resume.
     */
    @Query(
        "UPDATE transfers SET status = 'FAILED', cause = 'CANCELLED', updatedAtMs = :now " +
            "WHERE status IN ('QUEUED', 'PAUSED', 'RUNNING')",
    )
    suspend fun cancelActive(now: Long)

    /** File ids already on the device, so a selection can say "3 already here". */
    @Query("SELECT fileId FROM transfers WHERE status = 'DONE'")
    fun observeDoneFileIds(): Flow<List<Long>>
}

