/**
 * A chapter name the library holds, with how many films carry it. Used both
 * for the moment filter and for the editor's naming suggestions.
 */
data class UserChapterFacetRow(val title: String, val films: Int)

@Dao
interface UserChapterDao {
    @Query("SELECT * FROM user_chapters WHERE fileId = :fileId ORDER BY startMs")
    fun observeForFile(fileId: Long): Flow<List<UserChapterEntity>>

    @Insert
    suspend fun insertAll(rows: List<UserChapterEntity>)

    @Query("DELETE FROM user_chapters WHERE fileId = :fileId")
    suspend fun deleteForFile(fileId: Long)

    /**
     * A file's chapters are one value, so they are written as one: the old
     * set goes and the new one lands in the same transaction, and an
     * observer sees either the whole old list or the whole new one.
     */
    @Transaction
    suspend fun replaceForFile(fileId: Long, rows: List<UserChapterEntity>) {
        deleteForFile(fileId)
        if (rows.isNotEmpty()) insertAll(rows)
    }

    @Query("DELETE FROM user_chapters")
    suspend fun deleteAll()

    /** The films carrying any mark, so a bulk clear knows whose frames to drop. */
    @Query("SELECT DISTINCT fileId FROM user_chapters")
    suspend fun filesWithChapters(): List<Long>

    @Query("SELECT * FROM user_chapters WHERE fileId = :fileId ORDER BY startMs")
    suspend fun forFile(fileId: Long): List<UserChapterEntity>

    /** When this film's rows were last written, for the newest-wins rule. */
    @Query("SELECT MAX(updatedAtMs) FROM user_chapters WHERE fileId = :fileId")
    suspend fun lastUpdated(fileId: Long): Long?

    @Query("SELECT COUNT(*) AS chapters, COUNT(DISTINCT fileId) AS files FROM user_chapters")
    fun observeTally(): Flow<UserChapterTally>

    /**
     * Named chapters whose name matches, on files that are still on the
     * share. The film's name and parsed title ride along so the result can
     * be shown without a second query per row.
     */
    @Query(
        "SELECT user_chapters.fileId AS fileId, user_chapters.startMs AS startMs, user_chapters.title AS title, " +
            "media_files.name AS fileName, media_files.titleParsed AS fileTitle, media_files.shareId AS shareId, media_files.relPath AS fileRelPath " +
            "FROM user_chapters JOIN user_chapter_fts ON user_chapters.id = user_chapter_fts.rowid " +
            "JOIN media_files ON media_files.id = user_chapters.fileId " +
            "WHERE user_chapter_fts MATCH :match AND user_chapters.title IS NOT NULL AND media_files.missing = 0 " +
            "ORDER BY media_files.name, user_chapters.startMs LIMIT :limit",
    )
    fun search(match: String, limit: Int): Flow<List<UserChapterHitRow>>

    /**
     * Every named chapter in the library, commonest first. The names arrive
     * from both directions — typed in the editor, or imported from a
     * `.chapters.txt` beside the film — because both land in this table, so
     * this sees the whole library without reading a share.
     *
     * `COLLATE NOCASE` on the grouping so "The Heist" and "the heist" are
     * one chip; `MIN(title)` picks a stable spelling to show.
     *
     * This used to end `HAVING films > 1`, on the theory that a name on a
     * single film filters nothing. It does filter something — down to that
     * one film — and leaving it out made the list look broken, because a
     * moment you had just written was missing from it.
     */
    @Query(
        "SELECT MIN(user_chapters.title) AS title, COUNT(DISTINCT user_chapters.fileId) AS films " +
            "FROM user_chapters JOIN media_files ON media_files.id = user_chapters.fileId " +
            "WHERE user_chapters.title IS NOT NULL AND user_chapters.title != '' AND media_files.missing = 0 " +
            "GROUP BY user_chapters.title COLLATE NOCASE " +
            "ORDER BY films DESC, title COLLATE NOCASE LIMIT :limit",
    )
    fun observeFacets(limit: Int): Flow<List<UserChapterFacetRow>>

    /**
     * The same list, narrowed to the names matching what is being typed —
     * through `user_chapter_fts`, the index the chapter search already uses,
     * so "hei" reaches "The heist" exactly as it does in Search.
     *
     * Grouped rather than listed per occurrence: the editor is suggesting a
     * NAME, so "The heist" on four films is one suggestion, not four.
     */
    @Query(
        "SELECT MIN(user_chapters.title) AS title, COUNT(DISTINCT user_chapters.fileId) AS films " +
            "FROM user_chapters JOIN user_chapter_fts ON user_chapters.id = user_chapter_fts.rowid " +
            "JOIN media_files ON media_files.id = user_chapters.fileId " +
            "WHERE user_chapter_fts MATCH :match AND user_chapters.title IS NOT NULL AND user_chapters.title != '' " +
            "AND media_files.missing = 0 " +
            "GROUP BY user_chapters.title COLLATE NOCASE " +
            "ORDER BY films DESC, title COLLATE NOCASE LIMIT :limit",
    )
    fun observeNameMatches(match: String, limit: Int): Flow<List<UserChapterFacetRow>>

    /** The films carrying a chapter of this exact name, for a chip's own listing. */
    @Query(
        "SELECT media_files.* FROM media_files JOIN user_chapters ON user_chapters.fileId = media_files.id " +
            "WHERE user_chapters.title = :title COLLATE NOCASE AND media_files.missing = 0 " +
            "GROUP BY media_files.id ORDER BY media_files.name LIMIT :limit",
    )
    fun filesWithChapter(title: String, limit: Int): Flow<List<MediaFileEntity>>

    /**
     * Every occurrence of one point of interest, so a chip can list the
     * moments themselves rather than the files holding them. Same shape as
     * [search], matched on the exact name instead of through the index.
     */
    @Query(
        "SELECT user_chapters.fileId AS fileId, user_chapters.startMs AS startMs, user_chapters.title AS title, " +
            "media_files.name AS fileName, media_files.titleParsed AS fileTitle, media_files.shareId AS shareId, media_files.relPath AS fileRelPath " +
            "FROM user_chapters JOIN media_files ON media_files.id = user_chapters.fileId " +
            "WHERE user_chapters.title = :title COLLATE NOCASE AND media_files.missing = 0 " +
            "ORDER BY media_files.name, user_chapters.startMs LIMIT :limit",
    )
    fun occurrencesOf(title: String, limit: Int): Flow<List<UserChapterHitRow>>
}

