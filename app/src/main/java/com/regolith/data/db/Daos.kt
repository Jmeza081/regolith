    @Insert
    suspend fun insert(artwork: ArtworkEntity): Long

    @Update
    suspend fun update(artwork: ArtworkEntity)

    /** Replace by (ownerType, ownerId, ownerVariant, kind); the row id is not meaningful to anyone. */
