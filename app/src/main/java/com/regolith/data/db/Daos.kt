@Dao
interface FolderDao {
    @Query("SELECT * FROM folders WHERE id = :id")
    suspend fun byId(id: Long): FolderEntity?

    @Query("SELECT * FROM folders WHERE id = :id")
    fun observe(id: Long): Flow<FolderEntity?>

    @Query("SELECT * FROM folders WHERE shareId = :shareId AND relPath = :relPath")
    suspend fun byPath(shareId: Long, relPath: String): FolderEntity?

    @Query("SELECT * FROM folders WHERE parentId = :parentId ORDER BY name COLLATE NOCASE")
    fun observeChildren(parentId: Long): Flow<List<FolderEntity>>

    @Insert
    suspend fun insert(folder: FolderEntity): Long

    @Update
    suspend fun update(folder: FolderEntity)

    @Query("DELETE FROM folders WHERE parentId = :parentId AND relPath NOT IN (:keepPaths)")
    suspend fun deleteChildrenNotIn(parentId: Long, keepPaths: List<String>)

    /** Returns the row for (shareId, relPath), creating it if needed. Ids never change. */
    @Transaction
    suspend fun upsert(folder: FolderEntity): FolderEntity {
        val existing = byPath(folder.shareId, folder.relPath) ?: return folder.copy(id = insert(folder))
        // A parent's listing re-upserts its children before they are walked (lastListedAtMs null):
        // that must not wipe the counts the child's own listing wrote earlier.
        val listed = folder.lastListedAtMs != null
        val merged = existing.copy(
            name = folder.name,
            // A folder can change parent without changing path: a share
            // narrowed to chosen folders rebuilds the rows on the way down to
            // them, and a row written by an earlier build may be hanging off
            // the wrong one.
            parentId = folder.parentId,
            fileCount = if (listed) folder.fileCount else existing.fileCount,
            byteCount = if (listed) folder.byteCount else existing.byteCount,
            lastListedAtMs = folder.lastListedAtMs ?: existing.lastListedAtMs,
            kind = folder.kind ?: existing.kind,
            titleParsed = folder.titleParsed ?: existing.titleParsed,
            year = folder.year ?: existing.year,
        )
        update(merged)
        return merged
    }

    @Query("UPDATE folders SET kind = :kind, titleParsed = :titleParsed, year = :year WHERE id = :id")
    suspend fun setKind(id: Long, kind: String, titleParsed: String?, year: Int?)

    @Query("SELECT * FROM folders WHERE shareId IN (:shareIds) AND parentId IS NULL")
    fun observeRoots(shareIds: List<Long>): Flow<List<FolderEntity>>

    @Query("SELECT * FROM folders WHERE shareId IN (:shareIds) ORDER BY name COLLATE NOCASE")
    fun observeInShares(shareIds: List<Long>): Flow<List<FolderEntity>>

    @Query("SELECT * FROM folders WHERE parentId = :parentId")
    suspend fun children(parentId: Long): List<FolderEntity>

    @Query("SELECT folders.* FROM folders JOIN folder_fts ON folders.id = folder_fts.rowid WHERE folder_fts MATCH :match AND folders.parentId IS NOT NULL LIMIT :limit")
    fun searchFolders(match: String, limit: Int): Flow<List<FolderEntity>>

    /**
     * Drop folder rows outright — a folder the user deleted off the share.
     *
     * `media_files` has a CASCADE foreign key on `folderId`, so the files
     * inside go with them, and their chapters, progress and transfers
     * cascade in turn. `folders.parentId` has NO such key, so subfolders do
     * NOT follow: the caller passes the whole subtree.
     */
    @Query("DELETE FROM folders WHERE id IN (:ids)")
    suspend fun deleteByIds(ids: List<Long>)

    /** Every folder id there is, for the startup sweep. */
    @Query("SELECT id FROM folders")
    suspend fun allIds(): List<Long>
}

/**
 * The local mirror's half of a folder move or rename.
 *
 * On the share this is ONE metadata operation: the server renames the
 * directory and every path beneath it follows, with nothing copied. Room
 * has no such luxury — `relPath` is denormalised onto every folder and file
 * row, so all of them are now wrong, and `share_roots` (the chosen-folders
 * allowlist) can be pointing at the old path too.
 *
 * Three UPDATEs rather than a row-per-loop, and one [Transaction] around
 * them, so a subtree of any size is a single statement each and the mirror
 * is never half-rewritten. `substr` rather than `LIKE` because a folder may
 * legitimately be called `Season_01` or `100%`, and those are wildcards to
 * `LIKE`.
 *
 * Room's FTS tables are external-content with triggers in SQLite itself, so
 * they re-index from these UPDATEs without being told.
 */
@Dao
interface SubtreeDao {

    /**
     * Repoint [folderId] and everything under it, from [oldPath] to [newPath].
     *
     * [newParentId] is where the folder now hangs (unchanged for a rename);
     * [newName] is its last segment.
     */
    @Transaction
    suspend fun relocate(
        folderId: Long,
        shareId: Long,
        oldPath: String,
        newPath: String,
        newName: String,
        newParentId: Long?,
    ) {
        moveFolderRow(folderId, newPath, newName, newParentId)
        val oldPrefix = "$oldPath/"
        val newPrefix = "$newPath/"
        val cut = oldPrefix.length
        rewriteFolderPaths(shareId, oldPrefix, newPrefix, cut, cut + 1)
        rewriteFilePaths(shareId, oldPrefix, newPrefix, cut, cut + 1)
        rewriteRootPaths(shareId, oldPath, newPath, oldPrefix, newPrefix, cut, cut + 1)
    }

    @Query("UPDATE folders SET relPath = :newPath, name = :newName, parentId = :newParentId WHERE id = :id")
    suspend fun moveFolderRow(id: Long, newPath: String, newName: String, newParentId: Long?)

    @Query(
        "UPDATE folders SET relPath = :newPrefix || substr(relPath, :from) " +
            "WHERE shareId = :shareId AND substr(relPath, 1, :cut) = :oldPrefix",
    )
    suspend fun rewriteFolderPaths(shareId: Long, oldPrefix: String, newPrefix: String, cut: Int, from: Int)

    @Query(
        "UPDATE media_files SET relPath = :newPrefix || substr(relPath, :from) " +
            "WHERE shareId = :shareId AND substr(relPath, 1, :cut) = :oldPrefix",
    )
    suspend fun rewriteFilePaths(shareId: Long, oldPrefix: String, newPrefix: String, cut: Int, from: Int)

    /**
     * A chosen root that WAS the folder, or sat inside it, follows it.
     * Otherwise narrowing a library to `Films/Kids` and then moving that
     * folder would quietly empty the library.
     */
    @Query(
        "UPDATE share_roots SET relPath = CASE WHEN relPath = :oldPath THEN :newPath " +
            "ELSE :newPrefix || substr(relPath, :from) END " +
            "WHERE shareId = :shareId AND (relPath = :oldPath OR substr(relPath, 1, :cut) = :oldPrefix)",
    )
    suspend fun rewriteRootPaths(shareId: Long, oldPath: String, newPath: String, oldPrefix: String, newPrefix: String, cut: Int, from: Int)

    /** A deleted folder takes its chosen-root rows with it; nothing points at it any more. */
    @Query("DELETE FROM share_roots WHERE shareId = :shareId AND (relPath = :path OR substr(relPath, 1, :cut) = :prefix)")
    suspend fun dropRootsUnder(shareId: Long, path: String, prefix: String, cut: Int)
}

@Dao
interface MediaFileDao {
    @Query("SELECT * FROM media_files WHERE id = :id")
    suspend fun byId(id: Long): MediaFileEntity?

    @Query("SELECT * FROM media_files WHERE id = :id")
    fun observe(id: Long): Flow<MediaFileEntity?>

    @Query("SELECT * FROM media_files WHERE id = :id")
    fun byIdBlocking(id: Long): MediaFileEntity?

    /**
     * Every present file directly inside any of [folderIds].
     *
     * Called per chunk by `LibraryRepository.filesUnder`, because SQLite
     * caps a statement at 999 bound variables and a share can have
     * thousands of folders. `missing = 0` keeps rows a rescan flagged as
     * gone off the share out of a download.
     */
    @Query("SELECT * FROM media_files WHERE folderId IN (:folderIds) AND missing = 0 ORDER BY name COLLATE NOCASE")
    suspend fun inFolders(folderIds: List<Long>): List<MediaFileEntity>

    @Query("SELECT * FROM media_files WHERE shareId = :shareId AND relPath = :relPath")
    suspend fun byPath(shareId: Long, relPath: String): MediaFileEntity?

    /**
     * Files under [serverId] that have a finished copy on this device.
     *
     * The rows a disconnect ADOPTS rather than cascades away
     * ([com.regolith.domain.media.DeviceSource]). Joined through `shares`
     * because a transfer knows its file, and a file knows its share, but
     * neither knows its server.
     */
    @Query(
        "SELECT media_files.* FROM media_files " +
            "JOIN shares ON shares.id = media_files.shareId " +
            "JOIN transfers ON transfers.fileId = media_files.id " +
            "WHERE shares.serverId = :serverId AND transfers.status = 'DONE'",
    )
    suspend fun downloadedUnderServer(serverId: Long): List<MediaFileEntity>

    /** The same count, for the sentence the disconnect dialog has to be able to promise. */
    @Query(
        "SELECT COUNT(*) FROM media_files " +
            "JOIN shares ON shares.id = media_files.shareId " +
            "JOIN transfers ON transfers.fileId = media_files.id " +
            "WHERE shares.serverId = :serverId AND transfers.status = 'DONE'",
    )
    suspend fun downloadedCountUnderServer(serverId: Long): Int

    /** Every transfer row under [serverId], finished or not, so the bytes of the unfinished ones can go. */
    @Query(
        "SELECT transfers.* FROM transfers " +
            "JOIN media_files ON media_files.id = transfers.fileId " +
            "JOIN shares ON shares.id = media_files.shareId " +
            "WHERE shares.serverId = :serverId",
    )
    suspend fun transfersUnderServer(serverId: Long): List<TransferEntity>

    /** How many files a share holds, missing or not — the sweep's test for an empty "This device". */
    @Query("SELECT COUNT(*) FROM media_files WHERE shareId = :shareId")
    suspend fun countInShare(shareId: Long): Int

    /** Every file id there is, for the startup sweep's "does anything still own this directory?". */
    @Query("SELECT id FROM media_files")
    suspend fun allIds(): List<Long>

    @Query("SELECT * FROM media_files WHERE folderId = :folderId AND missing = 0 ORDER BY name COLLATE NOCASE")
    fun observeInFolder(folderId: Long): Flow<List<MediaFileEntity>>

    @Query("SELECT * FROM media_files WHERE folderId = :folderId AND missing = 0 ORDER BY name COLLATE NOCASE")
    suspend fun inFolder(folderId: Long): List<MediaFileEntity>

    /**
     * A playback queue's files, in whatever order SQLite returns them; the
     * caller re-orders to match the queue, which is the order you saw on the
     * wall and not one the database knows about.
     */
    @Query("SELECT * FROM media_files WHERE id IN (:ids) AND missing = 0")
    suspend fun byIds(ids: List<Long>): List<MediaFileEntity>

    @Insert
    suspend fun insert(file: MediaFileEntity): Long

    @Update
    suspend fun update(file: MediaFileEntity)

    @Query("UPDATE media_files SET missing = 1 WHERE folderId = :folderId AND relPath NOT IN (:seenPaths)")
    suspend fun markMissingNotIn(folderId: Long, seenPaths: List<String>)

    /**
     * The user deleted these from the share, so the rows go — unlike a
     * rescan, which only marks missing (guardrail G3). Progress, chapters,
     * artwork and any transfer row cascade away with them, which is exactly
     * what the confirm dialog promises.
     */
    @Query("DELETE FROM media_files WHERE id IN (:ids)")
    suspend fun deleteByIds(ids: List<Long>)

    /** What frame extraction learns in passing; never overwrites a value the full probe set. */
    @Query(
        "UPDATE media_files SET durationMs = COALESCE(durationMs, :durationMs), width = COALESCE(width, :width), height = COALESCE(height, :height), " +
            "rotationDegrees = COALESCE(rotationDegrees, :rotationDegrees) WHERE id = :id",
    )
    suspend fun fillBasics(id: Long, durationMs: Long?, width: Int?, height: Int?, rotationDegrees: Int?)

    /** The full container probe (Title Detail). */
    @Query(
        "UPDATE media_files SET durationMs = COALESCE(:durationMs, durationMs), width = :width, height = :height, rotationDegrees = :rotationDegrees, frameRate = :frameRate, " +
            "videoCodec = :videoCodec, hdr = :hdr, audioCodec = :audioCodec, audioChannels = :audioChannels, audioSampleRate = :audioSampleRate, probedAtMs = :probedAtMs WHERE id = :id",
    )
    suspend fun saveProbe(
        id: Long,
        durationMs: Long?,
        width: Int?,
        height: Int?,
        rotationDegrees: Int?,
        frameRate: Float?,
        videoCodec: String?,
        hdr: Boolean?,
        audioCodec: String?,
        audioChannels: Int?,
        audioSampleRate: Int?,
        probedAtMs: Long,
    )

    /**
     * Insert or refresh by (shareId, relPath). A file that reappears after
     * being marked missing gets its row (and therefore its progress) back.
     */
    @Transaction
    suspend fun upsert(file: MediaFileEntity): MediaFileEntity {
        val existing = byPath(file.shareId, file.relPath) ?: return file.copy(id = insert(file))
        val merged = existing.copy(
            folderId = file.folderId,
            name = file.name,
            ext = file.ext,
            sizeBytes = file.sizeBytes,
            modifiedAtMs = file.modifiedAtMs,
            missing = false,
            lastSeenAtMs = file.lastSeenAtMs,
            titleParsed = file.titleParsed ?: existing.titleParsed,
            year = file.year ?: existing.year,
            season = file.season ?: existing.season,
            episode = file.episode ?: existing.episode,
        )
        update(merged)
        return merged
    }

    @Query("SELECT * FROM media_files WHERE folderId IN (:folderIds) AND missing = 0 ORDER BY name COLLATE NOCASE")
    fun observeInFolders(folderIds: List<Long>): Flow<List<MediaFileEntity>>

    @Query("SELECT * FROM media_files WHERE id IN (:ids)")
    fun observeByIds(ids: List<Long>): Flow<List<MediaFileEntity>>

    /** Everything under a share, for Library counts and "files under this collection". */
    @Query("SELECT * FROM media_files WHERE shareId IN (:shareIds) AND missing = 0")
    fun observeInShares(shareIds: List<Long>): Flow<List<MediaFileEntity>>

    @Query("SELECT COUNT(*) FROM media_files WHERE shareId IN (:shareIds) AND missing = 0")
    fun observeCountInShares(shareIds: List<Long>): Flow<Int>

    /**
     * Candidates for the Shorts feed: present, measured, and short enough.
     *
     * The shape of the rule is deliberately split. SQLite does the half it
     * is good at -- a duration bound, which throws away almost everything on
     * a media share -- and the rotation-aware "is it portrait" half runs in
     * Kotlin (`ShortsRule`), where it is testable without a database. No
     * index on `durationMs`: the remaining scan is a few thousand rows, and
     * an index would cost a schema version to save nothing measurable.
     */
    @Query(
        "SELECT * FROM media_files WHERE shareId IN (:shareIds) AND missing = 0 " +
            "AND durationMs IS NOT NULL AND durationMs > 0 AND durationMs <= :maxDurationMs " +
            "AND width IS NOT NULL AND height IS NOT NULL " +
            "ORDER BY addedAtMs DESC, id DESC",
    )
    fun observeShortCandidates(shareIds: List<Long>, maxDurationMs: Long): Flow<List<MediaFileEntity>>

    /** Newest files first (Home's "Newly added"). */
    @Query("SELECT * FROM media_files WHERE missing = 0 ORDER BY addedAtMs DESC, id DESC LIMIT :limit")
    fun observeNewest(limit: Int): Flow<List<MediaFileEntity>>

    /** Files with unfinished progress, most recently watched first (Home's "Continue watching"). */
    @Query(
        "SELECT media_files.* FROM media_files JOIN playback_progress ON playback_progress.fileId = media_files.id " +
            "WHERE media_files.missing = 0 AND playback_progress.completed = 0 AND playback_progress.positionMs > 0 " +
            "ORDER BY playback_progress.updatedAtMs DESC LIMIT :limit",
    )
    fun observeContinueWatching(limit: Int): Flow<List<MediaFileEntity>>

    @Query("SELECT media_files.* FROM media_files JOIN media_fts ON media_files.id = media_fts.rowid WHERE media_fts MATCH :match AND media_files.missing = 0 LIMIT :limit")
    fun search(match: String, limit: Int): Flow<List<MediaFileEntity>>
}

